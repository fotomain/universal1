export interface BudgetItemJSON { title: string; description?: string | null; managementGenusItem: string | null }

const isSet = (g: unknown): g is string => typeof g === 'string' && g !== '' && g !== 'empty';

/** a folder = a top level row (level 1); everything below is an item */
export const isBudgetItemFolder = (r: DefRow<any>) => !isSet(r.rowParentGUID);
export const budgetItemFolders = (rows: DefRow<any>[]) => (rows || []).filter(isBudgetItemFolder);
/** the budget items (level 2) */
export const budgetItems = (rows: DefRow<any>[]) => (rows || []).filter((r) => !isBudgetItemFolder(r));

/** the FOLDERS as tree nodes (title, order); the items are the rows of the table */
export function budgetItemNodes(rows: DefRow<any>[]): FolderTreeNode[] {
  return budgetItemFolders(rows).map((r) => ({
    id: r.rowGUID,
    parentId: null,
    title: String(r.rowJSON?.title ?? '').trim() || '(no title)',
    order: Number(r.orderInList) || 0,
  }));
}

/** 'Costs › Time' */
export function budgetItemPath(rows: DefRow<any>[], guid: string | null | undefined): string {
  const byId = new Map((rows || []).map((r) => [r.rowGUID, r]));
  const parts: string[] = [];
  const seen = new Set<string>();
  let g = guid;
  while (isSet(g) && !seen.has(g)) {
    seen.add(g);
    const r = byId.get(g);
    if (!r) { parts.unshift(g); break; }
    parts.unshift(String(r.rowJSON?.title ?? '').trim() || r.rowGUID);
    g = r.rowParentGUID;
  }
  return parts.join(' › ');
}

/** the genus an item can have: the LEVEL 2 rows of managementGenusTable */
export const budgetItemGenusOptions = (genusRows: DefRow<any>[]): { value: string; label: string }[] =>
  (genusRows || [])
    .filter((g) => !isManagementGenusFolder(g))
    .slice()
    .sort((a, b) => (Number(a.orderInList) || 0) - (Number(b.orderInList) || 0))
    .map((g) => ({ value: g.rowGUID, label: pathLabel(genusRows, g.rowGUID) }));

function pathLabel(genusRows: DefRow<any>[], guid: string): string {
  return budgetItemPath(genusRows, guid) || guid;
}

/**
 * The obligatory managementGenusItem: null = ok, else the message. `genusRows` = managementGenusTable; an empty list (not loaded yet) only checks
 * that a value is set, so a slow read never refuses a valid value.
 */
export function budgetItemGenusError(genusItem: unknown, genusRows: DefRow<any>[]): string | null {
  if (!isSet(genusItem)) return 'A budget item needs a management genus (managementGenusItem)';
  if (!genusRows || genusRows.length === 0) return null;
  const g = genusRows.find((r) => r.rowGUID === genusItem);
  if (!g) return `Management genus "${genusItem}" does not exist`;
  if (isManagementGenusFolder(g)) return `"${genusItem}" is a genus folder: pick a genus item`;
  return null;
}

/** the items without a valid genus (shown as a warning on the screen) */
export const budgetItemsWithoutGenus = (rows: DefRow<any>[], genusRows: DefRow<any>[]): DefRow<any>[] =>
  budgetItems(rows).filter((r) => budgetItemGenusError(r.rowJSON?.managementGenusItem, genusRows) !== null);

/** the items of one genus (a Time task line offers the items of timeGenus) */
export const budgetItemsOfGenus = (rows: DefRow<any>[], genusGUID: string): DefRow<any>[] =>
  budgetItems(rows).filter((r) => r.rowJSON?.managementGenusItem === genusGUID);

/** the item and every item / folder below it */
export function budgetItemDescendants(rows: DefRow<any>[], guid: string): Set<string> {
  const out = new Set<string>([guid]);
  let grew = true;
  while (grew) {
    grew = false;
    for (const r of rows || []) if (!out.has(r.rowGUID) && out.has(r.rowParentGUID)) { out.add(r.rowGUID); grew = true; }
  }
  return out;
}
