// Budget item - the budget articles a task line is budgeted as (Time, Material, Expense, Revenue, Payments ...). Two levels in ONE table, the shape of
// managementGenusTable:
//   folders (level 1)  costsBudgetFolder · revenuesBudgetFolder · paymentsBudgetFolder                 rowParentGUID 'empty'
//   items   (level 2)  timeBudgetItem, materialBudgetItem, expenseBudgetItem · revenueBudgetItem · inboundPaymentBudgetItem, outboundPaymentBudgetItem
//                                                                                                      rowParentGUID = its folder
//   budgetItemTable   rowGUID = the code · rowOwnerGUID 'budgetItemCatalog' · rowParentGUID = folder | 'empty' · rowJSON { title, description, managementGenusItem,
//                     budgetItemGenericKey, direction, isCorrection, isPolicyItem, webIfrsName, d365foName, sapName }
//   rowJSON.budgetItemGenericKey is OBLIGATORY on an item = '<activity>.<management genus>' (operating / investing / financing x genus, budgetItemKeyModel.ts); rowJSON.direction = inbound |
//   outbound (default = the direction of the key; only an item marked isCorrection may differ). webIfrsName / d365foName / sapName = how the item is named in IFRS (IAS 7), D365 FO, SAP.
//   isPolicyItem = IAS 7 lets the company choose the activity (interest, dividends). SQL PART 32 defaults an old item to operatingActivity.<genus>.
//   rowJSON.managementGenusItem is OBLIGATORY on an item = the rowGUID of a LEVEL 2 row of managementGenusTable (timeGenus, materialGenus, ...):
//   the genus the item belongs to (a Time task line offers the items of timeGenus only). Folders have no genus.
//   The tree has a SECOND level made of the activity (operating / investing / financing) under every folder - virtual nodes, see budgetItemNodes (nothing is stored).
//   SQL: kit8/sql/init/create_budget_item_table.sql · Screen: PMBudgetItemCRUD · route BUDGET_ITEM_ROUTES.list
